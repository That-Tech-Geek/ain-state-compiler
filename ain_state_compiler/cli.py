def cmd_install_ollama(args):
    """
    Checks if Ollama is installed. If not, downloads and installs it,
    then pulls the default model (gemma3:1b).
    """
    _print("\n[*] Checking for Ollama installation...")

    if _check_command_exists("ollama"):
        _print("[+] Ollama is already installed and on PATH.")
    else:
        system = platform.system().lower()

        if system == "windows":
            _print("[*] Downloading Ollama Windows installer...")
            installer_url = "https://ollama.com/download/OllamaSetup.exe"
            installer_path = os.path.join(os.environ.get("TEMP", os.getcwd()), "OllamaSetup.exe")
            try:
                urllib.request.urlretrieve(installer_url, installer_path)
                _print(f"[+] Installer saved to {installer_path}")
                _print("[*] Running installer silently (requires admin)...")
                subprocess.run(
                    [installer_path, "/S"],
                    check=True,
                    shell=False,
                )
                _print("[+] Ollama installed successfully.")
            except Exception as e:
                _print(f"[!] Auto-install failed: {e}")
                _print(f"    Please install Ollama manually from: {installer_url}")
                return

        elif system == "linux":
            _print("[*] Installing Ollama via curl script (Linux)...")
            try:
                subprocess.run(
                    "curl -fsSL https://ollama.com/install.sh | sh",
                    shell=True,
                    check=True,
                )
                _print("[+] Ollama installed successfully.")
            except Exception as e:
                _print(f"[!] Auto-install failed: {e}")
                _print("    Please install Ollama manually: https://ollama.com/download")
                return

        elif system == "darwin":
            _print("[*] Installing Ollama via brew (macOS)...")
            try:
                subprocess.run(["brew", "install", "ollama"], check=True)
                _print("[+] Ollama installed successfully.")
            except Exception as e:
                _print(f"[!] Auto-install failed: {e}")
                _print("    Please install Ollama manually: https://ollama.com/download")
                return
        else:
            _print(f"[!] Unsupported OS: {system}. Please install Ollama manually.")
            return

    # Pull the default model
    model = getattr(args, "model", None) or "gemma3:1b"
    _print(f"\n[*] Pulling Ollama model: {model} (this may take a few minutes)...")
    try:
        subprocess.run(["ollama", "pull", model], check=True)
        _print(f"[+] Model '{model}' ready.")
    except FileNotFoundError:
        _print("[!] Ollama not found on PATH. Please restart your terminal and try again.")
    except subprocess.CalledProcessError as e:
        _print(f"[!] Model pull failed: {e}")


def cmd_cron(args):
    """
    Registers a background 5-minute sync task.
    Windows: Windows Task Scheduler (schtasks + PowerShell)
    Linux/macOS: crontab entry
    """
    project_dir = _find_project_dir()
    python_exec = sys.executable
    system = platform.system().lower()

    _print("\n[*] Setting up 5-minute background sync task...")

    if system == "windows":
        # Build the PowerShell command to register a scheduled task
        task_name = "AINBrainSync"
        script_path = os.path.join(project_dir, "_ain_cron_sync.bat")

        bat_content = f'@echo off\n"{python_exec}" -c "from ain_state_compiler.sync import sync_from_hivemind; sync_from_hivemind(r\'{project_dir}\')" >> "{os.path.join(project_dir, "sync.log")}" 2>&1\n'
        with open(script_path, "w", encoding="utf-8") as f:
            f.write(bat_content)

        ps_script = f"""
$trigger = New-ScheduledTaskTrigger -RepetitionInterval (New-TimeSpan -Minutes 5) -Once -At (Get-Date)
$action  = New-ScheduledTaskAction -Execute '"{script_path}"'
$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit (New-TimeSpan -Minutes 4) -StartWhenAvailable
Register-ScheduledTask -TaskName "{task_name}" -Trigger $trigger -Action $action -Settings $settings -RunLevel Highest -Force
"""
        ps_path = os.path.join(project_dir, "_register_task.ps1")
        with open(ps_path, "w", encoding="utf-8") as f:
            f.write(ps_script)

        _print(f"[*] Registering Windows Task Scheduler task '{task_name}' (needs Admin)...")
        try:
            result = subprocess.run(
                ["powershell", "-ExecutionPolicy", "Bypass", "-File", ps_path],
                capture_output=True,
                text=True,
            )
            if result.returncode == 0:
                _print(f"[+] Scheduled task '{task_name}' registered. Runs every 5 minutes.")
            else:
                _print(f"[!] Task Scheduler registration failed:\n{result.stderr.strip()}")
                _print(f"    You can register manually by running (as Admin):\n    powershell -File \"{ps_path}\"")
        except Exception as e:
            _print(f"[!] Failed to launch PowerShell: {e}")

    elif system in ("linux", "darwin"):
        sync_cmd = f'*/5 * * * * {python_exec} -c "from ain_state_compiler.sync import sync_from_hivemind; sync_from_hivemind(\'{project_dir}\')" >> {os.path.join(project_dir, "sync.log")} 2>&1'
        _print("[*] Adding crontab entry (requires user crontab access)...")
        try:
            existing = subprocess.run(
                ["crontab", "-l"],
                capture_output=True,
                text=True,
            )
            existing_crons = existing.stdout if existing.returncode == 0 else ""
            if "AINBrainSync" in existing_crons or "ain_state_compiler" in existing_crons:
                _print("[+] Cron entry already exists. Skipping.")
            else:
                new_crons = existing_crons.rstrip("\n") + f"\n# AINBrainSync\n{sync_cmd}\n"
                proc = subprocess.Popen(["crontab", "-"], stdin=subprocess.PIPE)
                proc.communicate(new_crons.encode("utf-8"))
                _print("[+] Cron job added. Sync will run every 5 minutes.")
        except Exception as e:
            _print(f"[!] crontab setup failed: {e}")
            _print(f"    Add this line to your crontab manually:\n    {sync_cmd}")
    else:
        _print(f"[!] Unsupported OS: {system}. Please configure the background task manually.")


def cmd_sync(args):
    """Run a one-shot sync + offline state compilation."""
    project_dir = _find_project_dir()
    _print("\n[*] Running one-shot hivemind sync + compile...")
    from ain_state_compiler.sync import sync_from_hivemind
    success = sync_from_hivemind(project_dir)
    if success:
        _print("[+] Sync and compilation complete.")
    else:
        _print("[!] Sync failed. Check credentials and database status.")


def cmd_query(args):
    """Ask the Company Brain a question on the CLI."""
    project_dir = _find_project_dir()
    query_text = " ".join(args.text)
    if not query_text:
        _print("[!] Please provide a query. Usage: ain-brain query <your question>")
        return

    _print(f"\n[*] Querying Company Brain: '{query_text}'")
    sys.path.insert(0, project_dir)

    # Try importing from installed package first, fall back to local file
    try:
        from ain_state_compiler.query import query_brain
    except ImportError:
        try:
            # Load old-style query_brain.py from project root
            import importlib.util
            spec = importlib.util.spec_from_file_location(
                "query_brain", os.path.join(project_dir, "query_brain.py")
            )
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            query_brain = mod.query_brain
        except Exception as e:
            _print(f"[!] Could not load query module: {e}")
            return

    ans, node, is_llm = query_brain(query_text)
    _print("\n======================================================")
    _print("  AIN COMPANY BRAIN - ANSWER")
    _print("======================================================")
    _print(f"  Context Node  : {node}")
    _print(f"  LLM Inference : {is_llm}")
    _print("------------------------------------------------------")
    _print(ans)
    _print("======================================================\n")


def cmd_init_db(args):
    """Seed the local SQLite hivemind database with mock data."""
    project_dir = _find_project_dir()
    _print("\n[*] Initializing local Hivemind database with seed data...")
    sys.path.insert(0, project_dir)
    try:
        import importlib.util
        init_path = os.path.join(project_dir, "init_hivemind_db.py")
        if os.path.exists(init_path):
            spec = importlib.util.spec_from_file_location("init_hivemind_db", init_path)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            mod.init_db()
        else:
            _print("[!] init_hivemind_db.py not found. Database not seeded.")
    except Exception as e:
        _print(f"[!] DB init failed: {e}")


def cmd_ingest(args):
    """
    Run full context harvest from all configured sources (Slack, Jira, Gmail).
    Uses credentials from .env file.
    Indexes all results into SQLite FTS5 (context_index.db).
    Prints readiness banner when done.
    """
    project_dir = _find_project_dir()
    _print("\n[*] Starting full context harvest...")
    try:
        from ain_state_compiler.ingest.orchestrator import orchestrate_ingest
        manifest = orchestrate_ingest(project_dir)
        _print(f"[+] Harvest complete. {manifest['grand_total_in_index']:,} records indexed.")
        _print(f"[+] Manifest saved: {os.path.join(project_dir, 'ingest_manifest.json')}")
    except Exception as e:
        _print(f"[!] Ingest failed: {e}")
        import traceback
        traceback.print_exc()


def cmd_server(args):
    """Start the REST API + Dashboard server."""
    project_dir = _find_project_dir()
    _print("\n[*] Starting AIN State Compiler server...")
    server_path = os.path.join(project_dir, "main.py")
    if not os.path.exists(server_path):
        _print(f"[!] main.py not found at {server_path}")
        return
    try:
        subprocess.run([sys.executable, server_path])
    except KeyboardInterrupt:
        _print("\n[*] Server stopped.")


