def _print(msg):
    """ASCII-safe print (avoids CP1252 crash on Windows terminals)."""
    try:
        print(msg)
    except UnicodeEncodeError:
        print(msg.encode("ascii", "replace").decode("ascii"))


def _find_project_dir():
    """Walk up from CWD to find the project root (contains mock_data/ or compiled_state/)."""
    cwd = os.getcwd()
    for candidate in [cwd] + [os.path.dirname(cwd)] * 4:
        if os.path.isdir(os.path.join(candidate, "mock_data")) or \
           os.path.isdir(os.path.join(candidate, "compiled_state")):
            return candidate
    return cwd


def _write_env(project_dir, env_vars):
    """Writes/updates .env file without overwriting existing values."""
    env_path = os.path.join(project_dir, ".env")

    existing = {}
    if os.path.exists(env_path):
        with open(env_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, _, v = line.partition("=")
                    existing[k.strip()] = v.strip()

    existing.update({k: v for k, v in env_vars.items() if v})

    with open(env_path, "w", encoding="utf-8") as f:
        f.write("# AIN State Compiler Configuration\n")
        f.write("# Generated by `ain-brain setup` -- edit manually if needed\n\n")
        for k, v in existing.items():
            f.write(f"{k}={v}\n")

    _print(f"[+] Credentials saved to {env_path}")


def _prompt(label, secret=False, default=""):
    """Prompts the user for a value, masking input if secret=True."""
    hint = f" [{default}]" if default else ""
    full_label = f"  {label}{hint}: "
    try:
        if secret:
            val = getpass.getpass(full_label)
        else:
            val = input(full_label)
        return val.strip() or default
    except (EOFError, KeyboardInterrupt):
        _print("\n[!] Setup cancelled.")
        sys.exit(0)


def _check_command_exists(cmd):
    """Returns True if cmd is on PATH."""
    try:
        subprocess.run(
            [cmd, "--version"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=5,
        )
        return True
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False


